class Producto{
  constructor(id, nombre, descripcion, categoria, precio, stock, imagen, creador, localidad, favorito){
    this.id = id;
    this.nombre = nombre;
    this.descripcion = descripcion;
    this.categoria = categoria;
    this.precio = precio;
    this.stock = stock;
    this.imagen = imagen;
    this.creador = creador;
    this.localidad = localidad;
    this.favorito = favorito;
  }
}
